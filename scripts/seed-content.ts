async function main() {
  for (const d of DOCS) {
    await prisma.content.upsert({
      where: { key: d.key },
      create: { key: d.key, title: d.title, body: d.body },
      update: { title: d.title, body: d.body },
    });
    console.log(`[content] upsert ${d.key}「${d.title}」body ${d.body.length} 字`);
  }
  console.log(`[content] 完成,共 ${DOCS.length} 条`);
  await prisma.$disconnect();
}

main().catch(async (e) => {
  console.error(e);
  await prisma.$disconnect();
  process.exit(1);
});
